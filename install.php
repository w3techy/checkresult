// Security: Prevent execution if already installed
if (file_exists('install.lock') || file_exists('config.php')) {
    die("Installation Locked: The application appears to be already installed. If you intend to reinstall, remove 'install.lock' and 'config.php' manually.");
}

$error_messages = [];
$success_message = '';
$install_complete = false;

if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['submit_install'])) {
    $db_host = trim($_POST['db_host'] ?? '');
    $db_name = trim($_POST['db_name'] ?? '');
    $db_user = trim($_POST['db_user'] ?? '');
    $db_pass = $_POST['db_pass'] ?? '';

    $site_name = trim($_POST['site_name'] ?? '');
    $site_description = trim($_POST['site_description'] ?? '');

    $admin_user = trim($_POST['admin_user'] ?? '');
    $admin_pass = $_POST['admin_pass'] ?? '';

    // Validate inputs
    if (empty($db_host)) $error_messages[] = "Database Host is required.";
    if (empty($db_name)) {
        $error_messages[] = "Database Name is required.";
    } elseif (!preg_match('/^[a-zA-Z0-9_]+$/', $db_name)) {
        $error_messages[] = "Database Name must contain only letters, numbers, and underscores.";
    }
    if (empty($db_user)) $error_messages[] = "Database Username is required.";
    if (empty($site_name)) $error_messages[] = "Site Name is required.";
    if (empty($admin_user)) $error_messages[] = "Admin Username is required.";
    if (empty($admin_pass) || strlen($admin_pass) < 6) {
        $error_messages[] = "Admin Password must be at least 6 characters long.";
    }

    if (empty($error_messages)) {
        // 1. Test database connection
        $temp_conn = @mysqli_connect($db_host, $db_user, $db_pass);
        if (!$temp_conn) {
            $error_messages[] = "Failed to connect to MySQL server: " . mysqli_connect_error();
        } else {
            // 2. Create database if it doesn't exist
            $sql_create_db = "CREATE DATABASE IF NOT EXISTS `" . $db_name . "` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci";
            if (!mysqli_query($temp_conn, $sql_create_db)) {
                $error_messages[] = "Failed to create database: " . mysqli_error($temp_conn);
            } elseif (!mysqli_select_db($temp_conn, $db_name)) {
                $error_messages[] = "Failed to select database: " . mysqli_error($temp_conn);
            } else {
                mysqli_set_charset($temp_conn, 'utf8mb4');

                // 3. Write config.php safely using var_export to prevent code injection
                $config_content = "<?php\n"
                    . "// Database Configuration - Generated by Installer\n"
                    . "\$db_host = " . var_export($db_host, true) . ";\n"
                    . "\$db_user = " . var_export($db_user, true) . ";\n"
                    . "\$db_pass = " . var_export($db_pass, true) . ";\n"
                    . "\$db_name = " . var_export($db_name, true) . ";\n\n"
                    . "\$conn = mysqli_connect(\$db_host, \$db_user, \$db_pass, \$db_name);\n"
                    . "if (!\$conn) {\n"
                    . "    error_log('Database connection error: ' . mysqli_connect_error());\n"
                    . "    die('Database connection error. Please verify your configuration in config.php.');\n"
                    . "}\n\n"
                    . "mysqli_set_charset(\$conn, 'utf8mb4');\n";

                if (@file_put_contents('config.php', $config_content) === false) {
                    $error_messages[] = "Could not write to `config.php`. Please verify file permissions.";
                } else {
                    // 4. Execute database schemas
                    $sql_files = ['sql/user.sql', 'sql/subjects.sql', 'sql/admin_users.sql', 'sql/results.sql'];
                    $schema_error = false;

                    foreach ($sql_files as $filepath) {
                        if (!file_exists($filepath) || !is_readable($filepath)) {
                            $error_messages[] = "SQL file not accessible: " . htmlspecialchars($filepath);
                            $schema_error = true;
                            break;
                        }
                        $sql_content = file_get_contents($filepath);
                        if ($sql_content === false) {
                            $error_messages[] = "Failed reading: " . htmlspecialchars($filepath);
                            $schema_error = true;
                            break;
                        }

                        if (mysqli_multi_query($temp_conn, $sql_content)) {
                            do {
                                if ($res = mysqli_store_result($temp_conn)) {
                                    mysqli_free_result($res);
                                }
                            } while (mysqli_more_results($temp_conn) && mysqli_next_result($temp_conn));
                        }

                        if (mysqli_errno($temp_conn)) {
                            $error_messages[] = "Database schema error in " . htmlspecialchars($filepath) . ": " . mysqli_error($temp_conn);
                            $schema_error = true;
                            break;
                        }
                    }

                    if (!$schema_error) {
                        // 5. Create or update administrator user
                        $admin_hash = password_hash($admin_pass, PASSWORD_DEFAULT);
                        $admin_stmt = mysqli_prepare($temp_conn, "INSERT INTO admin_users (username, password) VALUES (?, ?) ON DUPLICATE KEY UPDATE password = ?");
                        if ($admin_stmt) {
                            mysqli_stmt_bind_param($admin_stmt, "sss", $admin_user, $admin_hash, $admin_hash);
                            mysqli_stmt_execute($admin_stmt);
                            mysqli_stmt_close($admin_stmt);
                        }

                        // 6. Write site_meta.php safely
                        $site_meta_content = "<?php\n"
                            . "// Site Meta Configuration - Generated by Installer\n\n"
                            . "define('SITE_NAME', " . var_export($site_name, true) . ");\n"
                            . "define('SITE_DESCRIPTION', " . var_export($site_description, true) . ");\n";

                        if (@file_put_contents('site_meta.php', $site_meta_content) === false) {
                            $error_messages[] = "Could not write to `site_meta.php`. Please verify file permissions.";
                        } else {
                            // 7. Write install.lock
                            @file_put_contents('install.lock', 'Installation completed on: ' . date("Y-m-d H:i:s"));
                            $install_complete = true;
                            $success_message = "Installation completed successfully! You can now log in to the student portal or admin dashboard.";
                        }
                    }
                }
            }
            mysqli_close($temp_conn);
        }
    }
}
